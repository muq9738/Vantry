package desktop

// translateJA maps workbench Chinese/English UI copy to idiomatic Japanese,
// falling back to English when a specialized diagnostic phrase has no dedicated entry.
func translateJA(zh, en string) string {
	if ja, ok := jaByZH[zh]; ok {
		return ja
	}
	if ja, ok := jaByEN[en]; ok {
		return ja
	}
	if en != "" {
		return en
	}
	return zh
}

