// ReadClipboardMedia reads a PDF document or PNG image from the system clipboard
// (such as a macOS screenshot or copied PDF page in Preview) bounded to 8 MiB.
func ReadClipboardMedia(ctx context.Context) (data []byte, mimeType string, fileName string, found bool, err error) {
	return readClipboardMedia(ctx, clipboardDeps{
		goos:     runtime.GOOS,
		lookPath: exec.LookPath,
		run: func(ctx context.Context, spec CommandSpec) (commandOutput, error) {
			return runCommandOutput(ctx, spec, maxClipboardImageSize)
		},
		makeTempDir: func() (string, error) { return os.MkdirTemp("", "vantry-clipboard-") },
	})
}

func readClipboardMedia(ctx context.Context, deps clipboardDeps) ([]byte, string, string, bool, error) {
	if err := ctx.Err(); err != nil {
		return nil, "", "", false, err
	}
	switch deps.goos {
	case "darwin":
		return readDarwinClipboardMedia(ctx, deps)
	case "linux":
		return readLinuxClipboardMedia(ctx, deps)
	default:
		return nil, "", "", false, nil
	}
}

func readDarwinClipboardMedia(ctx context.Context, deps clipboardDeps) ([]byte, string, string, bool, error) {
	directory, err := deps.makeTempDir()
	if err != nil {
		return nil, "", "", false, fmt.Errorf("创建剪贴板临时目录：%w", err)
	}
	if err := os.Chmod(directory, 0o700); err != nil {
		_ = os.RemoveAll(directory)
		return nil, "", "", false, fmt.Errorf("保护剪贴板临时目录：%w", err)
	}
	defer os.RemoveAll(directory)
	path := filepath.Join(directory, "clipboard.bin")
	output, err := deps.run(ctx, CommandSpec{
		Name:  darwinScriptTool,
		Args:  []string{"-", path},
		Stdin: clipboardMediaScript,
	})
	if err != nil {
		return nil, "", "", false, fmt.Errorf("读取剪贴板：%w", err)
	}
	kind := strings.TrimSpace(string(output.stdout))
	switch kind {
	case clipboardPDFWritten:
		data, err := readClipboardPDFFile(path)
		_ = os.Remove(path)
		if err != nil {
			if errors.Is(err, fs.ErrNotExist) {
				return nil, "", "", false, nil
			}
			return nil, "", "", false, err
		}
		return data, clipboardPDFType, clipboardPDFName, true, nil
	case clipboardImageWritten:
		data, err := readClipboardImageFile(path)
		_ = os.Remove(path)
		if err != nil {
			if errors.Is(err, fs.ErrNotExist) {
				return nil, "", "", false, nil
			}
			return nil, "", "", false, err
		}
		return data, clipboardImageType, clipboardImageName, true, nil
	case clipboardImageNone:
		return nil, "", "", false, nil
	default:
		return nil, "", "", false, errors.New("读取剪贴板媒体失败")
	}
}

func readLinuxClipboardMedia(ctx context.Context, deps clipboardDeps) ([]byte, string, string, bool, error) {
	pdfCandidates := []CommandSpec{
		{Name: "wl-paste", Args: []string{"--type", clipboardPDFType, "--no-newline"}},
		{Name: "xclip", Args: []string{"-selection", "clipboard", "-target", clipboardPDFType, "-out"}},
	}
	for _, candidate := range pdfCandidates {
		executable, err := deps.lookPath(candidate.Name)
		if err != nil {
			continue
		}
		candidate.Name = executable
		output, err := deps.run(ctx, candidate)
		if err != nil {
			if ctxErr := ctx.Err(); ctxErr != nil {
				return nil, "", "", false, ctxErr
			}
			continue
		}
		if output.excess || len(output.stdout) > maxClipboardImageSize {
			return nil, "", "", false, errClipboardMediaTooLarge
		}
		if len(output.stdout) == 0 {
			continue
		}
		if err := validateClipboardPDF(output.stdout); err != nil {
			continue
		}
		return output.stdout, clipboardPDFType, clipboardPDFName, true, nil
	}
	return readLinuxClipboardImage(ctx, deps)
}

func readClipboardPDFFile(path string) ([]byte, error) {
	file, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer file.Close()
	info, err := file.Stat()
	if err != nil {
		return nil, err
	}
	if !info.Mode().IsRegular() {
		return nil, errors.New("剪贴板临时文件不是普通文件")
	}
	if info.Size() > maxClipboardImageSize {
		return nil, errClipboardMediaTooLarge
	}
	data, err := io.ReadAll(io.LimitReader(file, maxClipboardImageSize+1))
	if err != nil {
		return nil, err
	}
	if err := validateClipboardPDF(data); err != nil {
		return nil, err
	}
	return data, nil
}

func validateClipboardPDF(data []byte) error {
	if int64(len(data)) > maxClipboardImageSize {
		return errClipboardMediaTooLarge
	}
	head := data
	if len(head) > 1024 {
		head = head[:1024]
	}
	if !bytes.Contains(head, pdfSignature) {
		return errClipboardMediaNotPDF
	}
	return nil
}
